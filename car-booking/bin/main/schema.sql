CREATE TABLE BOOKING (
    ID                  VARCHAR(14) PRIMARY KEY,
    BOOKING_START_DATE  TIMESTAMP NOT NULL,
    BOOKING_END_DATE    TIMESTAMP NOT NULL,
    CAR_ID              VARCHAR(10) NOT NULL,
    CUSTOMER_ID         VARCHAR(10) NOT NULL,
    BOOKING_STATUS      BOOKING_STATUS_ENUM NOT NULL DEFAULT 'PENDING',
    DATE_CREATED          TIMESTAMP NOT NULL DEFAULT now(),
    DATE_UPDATED          TIMESTAMP NOT NULL DEFAULT now(),

    CONSTRAINT FK_CAR FOREIGN KEY (CAR_ID) REFERENCES car(id) ON DELETE CASCADE,
    CONSTRAINT FK_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES customer(ID) ON DELETE CASCADE
);


CREATE TABLE BILLING (
  ID                    VARCHAR(14) PRIMARY KEY,
  -- 1:1 relation to booking
  BOOKING_ID            VARCHAR(14) NOT NULL,
  TOTAL_BILLING_AMOUNT  NUMERIC(12,2) NOT NULL CHECK (TOTAL_BILLING_AMOUNT >= 0),
  BILLING_DUE_DATE      DATE NOT NULL,
  BILLING_STATUS        BILLING_STATUS_ENUM NOT NULL DEFAULT 'DUE',
  -- audit
  DATE_CREATED          TIMESTAMP NOT NULL DEFAULT now(),
  DATE_UPDATED          TIMESTAMP NOT NULL DEFAULT now(),

  CONSTRAINT FK_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING(ID) ON DELETE CASCADE
);