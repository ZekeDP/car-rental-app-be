DROP TABLE IF EXISTS BOOKING;
DROP TABLE IF EXISTS car;
DROP TABLE IF EXISTS CUSTOMER;
DROP TABLE IF EXISTS BILLING;

CREATE TYPE car_status_enum AS ENUM ('ACTIVE', 'MAINTENANCE', 'UNAVAILABLE');

CREATE TYPE IF NOT EXISTS BOOKING_STATUS_ENUM AS ENUM ('PENDING','CONFIRMED','CANCELLED');

CREATE TYPE IF NOT EXISTS BILLING_STATUS_ENUM AS ENUM ('DUE','PARTIAL','PAID','OVERDUE','REFUNDED');

CREATE TABLE car (
  id       VARCHAR(10) PRIMARY KEY,
  plate_number VARCHAR(10) UNIQUE NOT NULL,
  model    VARCHAR(255) NOT NULL,
  car_type     VARCHAR(20) NOT NULL,
  color    VARCHAR(20) NOT NULL, 
  year_model    SMALLINT,
  car_status   car_status_enum NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE CUSTOMER (
  -- identifiers & names
  ID             VARCHAR(10) PRIMARY KEY,
  FIRST_NAME     VARCHAR(50) NOT NULL,
  MIDDLE_NAME    VARCHAR(50),
  LAST_NAME      VARCHAR(50) NOT NULL,

  -- phone numbers
  MOBILE_NUMBER  VARCHAR(15)  NOT NULL,   -- raw user input, e.g., 09171234567
  MOBILE_E164    VARCHAR(20)  NOT NULL,   -- backend-normalized, canonical, e.g., +639171234567

  -- email & address
  EMAIL_ADDRESS  VARCHAR(50) UNIQUE NOT NULL,  -- case-insensitive unique
  CUSTOMER_ADDRESS     VARCHAR(200),

  -- audit
  DATE_CREATED     TIMESTAMP NOT NULL DEFAULT now(),
  DATE_UPDATED     TIMESTAMP NOT NULL DEFAULT now()

  -- simple checks kept inline
  -- CHECK (MOBILE_NUMBER ~ '^09\\d{9}$'),  -- PH local: 11 digits starting with 09
  -- UNIQUE (MOBILE_E164)                   -- canonical must be unique
);

